package guest

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// bootLayout is a guest's /boot: the installed kernels, where the
// /boot/vmlinuz link points (the kernel installed last), and grub.cfg.
type bootLayout struct {
	kernels []string
	link    string
	grub    string // grub.cfg's contents; "" writes none
	// grubUnreadable makes grub.cfg 0000 instead of the 0444 grub-mkconfig
	// leaves.
	grubUnreadable bool
}

func (l *bootLayout) write(t *testing.T, boot string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Join(boot, "grub"), 0o755); err != nil {
		t.Fatal(err)
	}
	for _, k := range l.kernels {
		// Ubuntu installs kernel images 0600: only their names are readable.
		if err := os.WriteFile(filepath.Join(boot, "vmlinuz-"+k), nil, 0o600); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(boot, "initrd.img-"+k), nil, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if l.link != "" {
		if err := os.Symlink("vmlinuz-"+l.link, filepath.Join(boot, "vmlinuz")); err != nil {
			t.Fatal(err)
		}
		if err := os.Symlink("initrd.img-"+l.link, filepath.Join(boot, "initrd.img")); err != nil {
			t.Fatal(err)
		}
	}
	if l.grub != "" {
		mode := os.FileMode(0o444)
		if l.grubUnreadable {
			mode = 0
		}
		cfg := filepath.Join(boot, "grub", "grub.cfg")
		if err := os.WriteFile(cfg, []byte(l.grub), 0o600); err != nil {
			t.Fatal(err)
		}
		if err := os.Chmod(cfg, mode); err != nil {
			t.Fatal(err)
		}
	}
}

// ubuntuGrubCfg is what grub-mkconfig writes on an Ubuntu cloud image, cut
// to what matters: 00_header's default selection (def is GRUB_DEFAULT) and
// 10_linux's entries, newest kernel first. linuxDir is "/boot", or "" for a
// separate /boot partition.
func ubuntuGrubCfg(def, linuxDir string, kernels ...string) string {
	var b strings.Builder
	b.WriteString(`#
# DO NOT EDIT THIS FILE
#
### BEGIN /etc/grub.d/00_header ###
if [ -s $prefix/grubenv ]; then
  set have_grubenv=true
  load_env
fi
if [ "${initrdfail}" = 2 ]; then
   set initrdfail=
elif [ "${initrdfail}" = 1 ]; then
   set next_entry="${prev_entry}"
   set prev_entry=
   save_env prev_entry
   if [ "${next_entry}" ]; then
      set initrdfail=2
   fi
fi
if [ "${next_entry}" ] ; then
   set default="${next_entry}"
   set next_entry=
   save_env next_entry
   set boot_once=true
else
   set default="` + def + `"
fi
function savedefault {
  if [ -z "${boot_once}" ]; then
    saved_entry="${chosen}"
    save_env saved_entry
  fi
}
function load_video {
  insmod all_video
}
### END /etc/grub.d/00_header ###

### BEGIN /etc/grub.d/10_linux ###
function gfxmode {
	set gfxpayload="${1}"
	if [ "${1}" = "keep" ]; then
		set vt_handoff=vt.handoff=7
	else
		set vt_handoff=
	fi
}
`)
	entry := func(indent, title, k string) {
		b.WriteString(indent + "menuentry '" + title + "' --class ubuntu --class gnu-linux --class gnu --class os $menuentry_id_option 'gnulinux-" + k + "-advanced-1234' {\n")
		b.WriteString(indent + "\trecordfail\n" + indent + "\tload_video\n" + indent + "\tinsmod ext2\n")
		b.WriteString(indent + "\tsearch --no-floppy --fs-uuid --set=root 1234\n")
		b.WriteString(indent + "\tlinux\t" + linuxDir + "/vmlinuz-" + k + " root=LABEL=cloudimg-rootfs ro  console=tty1 console=ttyS0 efi_pstore.pstore_disable=1\n")
		b.WriteString(indent + "\tinitrd\t" + linuxDir + "/initrd.img-" + k + "\n" + indent + "}\n")
	}
	entry("", "Ubuntu", kernels[0])
	b.WriteString("submenu 'Advanced options for Ubuntu' $menuentry_id_option 'gnulinux-advanced-1234' {\n")
	for _, k := range kernels {
		entry("\t", "Ubuntu, with Linux "+k, k)
		entry("\t", "Ubuntu, with Linux "+k+" (recovery mode)", k)
	}
	b.WriteString("}\n### END /etc/grub.d/10_linux ###\n")
	return b.String()
}

// runBootKernel runs boot_kernel under sh (dash on Ubuntu, as doctor does).
func runBootKernel(t *testing.T, l bootLayout) string {
	t.Helper()
	if _, err := exec.LookPath("sh"); err != nil {
		t.Skip("sh not available")
	}
	boot := filepath.Join(t.TempDir(), "boot")
	l.write(t, boot)
	out, err := exec.Command("sh", "-c", "set -u\n"+BootKernelShell(boot)+BootKernelFunc).CombinedOutput()
	if err != nil {
		t.Fatalf("boot_kernel failed: %v\n%s", err, out)
	}
	return strings.TrimSuffix(string(out), "\n")
}

// TestBootKernelIsWhatGrubBoots: the kernel installed last moves
// /boot/vmlinuz, but GRUB boots the newest; only GRUB's choice decides
// whether a reboot is pending.
func TestBootKernelIsWhatGrubBoots(t *testing.T) {
	cases := []struct {
		name string
		l    bootLayout
		want string
	}{
		{
			// guest_kernel hwe on a 24.04 VM: a GA linux-virtual update installed
			// 6.8.0-147 after the HWE 7.0 kernel.
			name: "24.04 GA update after HWE",
			l: bootLayout{kernels: []string{"6.8.0-147-generic", "7.0.0-38-generic"}, link: "6.8.0-147-generic",
				grub: ubuntuGrubCfg("0", "/boot", "7.0.0-38-generic", "6.8.0-147-generic")},
			want: "7.0.0-38-generic",
		},
		{
			name: "24.04 HWE update installed",
			l: bootLayout{kernels: []string{"6.8.0-147-generic", "7.0.0-38-generic", "7.0.0-40-generic"}, link: "7.0.0-40-generic",
				grub: ubuntuGrubCfg("0", "/boot", "7.0.0-40-generic", "7.0.0-38-generic", "6.8.0-147-generic")},
			want: "7.0.0-40-generic",
		},
		{
			// A VM created on 26.04: GA and HWE are the same 7.0 series.
			name: "26.04 kernel update",
			l: bootLayout{kernels: []string{"7.0.0-38-generic", "7.0.0-40-generic"}, link: "7.0.0-40-generic",
				grub: ubuntuGrubCfg("0", "/boot", "7.0.0-40-generic", "7.0.0-38-generic")},
			want: "7.0.0-40-generic",
		},
		{
			name: "separate /boot partition",
			l: bootLayout{kernels: []string{"7.0.0-38-generic", "7.0.0-40-generic"}, link: "7.0.0-38-generic",
				grub: ubuntuGrubCfg("0", "", "7.0.0-40-generic", "7.0.0-38-generic")},
			want: "7.0.0-40-generic",
		},
		{
			// grub.cfg is what GRUB reads: a kernel installed without update-grub
			// is not booted.
			name: "grub.cfg not regenerated",
			l: bootLayout{kernels: []string{"7.0.0-38-generic", "7.0.0-40-generic"}, link: "7.0.0-40-generic",
				grub: ubuntuGrubCfg("0", "/boot", "7.0.0-38-generic")},
			want: "7.0.0-38-generic",
		},
		{
			// A version sort, not a string sort: 6.8.0-99 is older than 6.8.0-147.
			name: "no grub.cfg: newest by version",
			l:    bootLayout{kernels: []string{"6.8.0-99-generic", "6.8.0-147-generic", "6.17.0-5-generic"}, link: "6.8.0-99-generic"},
			want: "6.17.0-5-generic",
		},
		{
			name: "unreadable grub.cfg: newest by version",
			l: bootLayout{kernels: []string{"6.8.0-147-generic", "7.0.0-38-generic"}, link: "6.8.0-147-generic",
				grub: ubuntuGrubCfg("0", "/boot", "6.8.0-147-generic"), grubUnreadable: true},
			want: "7.0.0-38-generic",
		},
		{
			// GRUB_DEFAULT=saved (or an index or title) is not followed.
			name: "another GRUB_DEFAULT: newest by version",
			l: bootLayout{kernels: []string{"6.8.0-147-generic", "7.0.0-38-generic"}, link: "6.8.0-147-generic",
				grub: ubuntuGrubCfg("${saved_entry}", "/boot", "6.8.0-147-generic")},
			want: "7.0.0-38-generic",
		},
		{
			name: "no kernel at all",
			l:    bootLayout{},
			want: "",
		},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if c.l.grubUnreadable && os.Geteuid() == 0 {
				t.Skip("root reads a 0000 file")
			}
			if got := runBootKernel(t, c.l); got != c.want {
				t.Errorf("boot_kernel = %q, want %q", got, c.want)
			}
		})
	}
}

// TestBootKernelPrintsOnlyAVersion: a name with characters no kernel version
// has is not printed.
func TestBootKernelPrintsOnlyAVersion(t *testing.T) {
	l := bootLayout{kernels: []string{"7.0.0-38-generic"},
		grub: strings.Replace(ubuntuGrubCfg("0", "/boot", "7.0.0-38-generic"), "/boot/vmlinuz-7.0.0-38-generic", "/boot/vmlinuz-7.0;$(x)", 1)}
	if got := runBootKernel(t, l); got != "" {
		t.Errorf("boot_kernel = %q, want nothing", got)
	}
}

// TestGuestKernelNoRebootAfterGAUpdateUnderHWE: the false "reboot pending"
// (the GA update moved /boot/vmlinuz to 6.8) is gone, and a real one stays.
func TestGuestKernelNoRebootAfterGAUpdateUnderHWE(t *testing.T) {
	gaAfterHWE := &bootLayout{kernels: []string{"6.8.0-147-generic", "7.0.0-38-generic"}, link: "6.8.0-147-generic",
		grub: ubuntuGrubCfg("0", "/boot", "7.0.0-38-generic", "6.8.0-147-generic")}
	r, _ := runKernelEnv(t, kernelEnv{kernel: GuestKernelHWE, osVersion: "24.04", running: "7.0.0-38-generic", dpkgHas: true, boot: gaAfterHWE})
	if len(r.Reboot) != 0 {
		t.Errorf("reboot = %q, want none: GRUB boots the running kernel", r.Reboot)
	}
	r, _ = runKernelEnv(t, kernelEnv{kernel: GuestKernelHWE, osVersion: "24.04", running: "6.8.0-147-generic", dpkgHas: true, boot: gaAfterHWE})
	if len(r.Reboot) != 1 || !strings.Contains(r.Reboot[0], "runs kernel 6.8.0-147-generic; the next boot starts 7.0.0-38-generic") {
		t.Errorf("reboot = %q, want the HWE kernel pending", r.Reboot)
	}
}
