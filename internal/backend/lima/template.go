// The rendered template below is the CONTAINMENT SURFACE: exactly one writable
// mount (the project tree at /lever), all automatic guest→host port-forwarding
// suppressed (lima forwards every guest listener to host 127.0.0.1 by default,
// so a jailed agent could squat host-loopback ports and impersonate local
// services), and lima's bundled containerd disabled. Do not add mounts or
// forwards without a security review.

package lima

import (
	"bytes"
	"runtime"
	"text/template"
)

const templateText = `# Generated by lever — the lima jail containment surface. Do not edit.
vmType: {{.VMType}}
{{- if eq .VMType "vz"}}
mountType: virtiofs
{{- end}}
images:
{{- range .Images}}
  - location: "{{.URL}}"
    arch: "{{.Arch}}"
    digest: "sha256:{{.SHA256}}"
{{- end}}
disk: {{.Disk}}
{{- if .CPUs}}
cpus: {{.CPUs}}
{{- end}}
{{- if .Memory}}
memory: {{printf "%q" .Memory}}
{{- end}}
{{- if and .NestedVirt (eq .VMType "qemu")}}
vmOpts:
  qemu:
    cpuType:
      x86_64: host
      aarch64: host
{{- end}}
mounts:
  - location: {{printf "%q" .ProjectTree}}
    mountPoint: "/lever"
    writable: true
containerd:
  system: false
  user: false
portForwards:
  - guestIP: "0.0.0.0"
    # explicit: auto-inference only since lima 2.0 (4d04ff37)
    guestIPMustBeZero: true
    guestPortRange: [1, 65535]
    # proto defaults to "tcp" when omitted; lima's builtin fallback forward rule
    # is proto: "any" and forwards UDP guest listeners too, so an omitted proto
    # here would leave UDP auto-forwarding unsuppressed.
    proto: "any"
    ignore: true
  - guestIP: "127.0.0.1"
    guestPortRange: [1, 65535]
    proto: "any"
    ignore: true
`

var tpl = template.Must(template.New("lima").Parse(templateText))

// GuestImage is one architecture's jail guest image. The URL must name a
// dated release so it keeps naming the bytes the digest pins: the "release/"
// alias moves with every refresh. Lima refuses a download that does not
// match SHA256.
type GuestImage struct {
	Arch, URL, SHA256 string
}

// GuestRelease is the Ubuntu release of the jail guest image.
const GuestRelease = "26.04"

// GuestImages are the pinned jail guest images, one per Lima arch. A newer
// serial affects only new VMs: Lima reads the image at create time.
var GuestImages = []GuestImage{
	{
		Arch:   "aarch64",
		URL:    "https://cloud-images.ubuntu.com/releases/resolute/release-20260927/ubuntu-26.04-server-cloudimg-arm64.img",
		SHA256: "63a93bd5a8d76e33b15ceb5daa3657bd79be804748051ab178e643b0f5da22e7",
	},
	{
		Arch:   "x86_64",
		URL:    "https://cloud-images.ubuntu.com/releases/resolute/release-20260927/ubuntu-26.04-server-cloudimg-amd64.img",
		SHA256: "8800651811af9a85465ad1d552add729947bb16488dddb4a9b5305a3d97332b2",
	},
}

// defaultDisk caps the Lima guest disk: Lima's own default is a grow-only
// 100GiB, which can silently fill a smaller host. Applied only at VM
// creation.
const defaultDisk = "24GiB"

// TemplateOpts are the per-instance values the template renders. Zero values
// select the defaults.
type TemplateOpts struct {
	Disk       string
	CPUs       int
	Memory     string
	NestedVirt bool
}

// RenderTemplate renders the jail VM template for this host OS.
func RenderTemplate(projectTree string, o TemplateOpts) (string, error) {
	if o.Disk == "" {
		o.Disk = defaultDisk
	}
	vmType := "qemu"
	if runtime.GOOS == "darwin" {
		vmType = "vz"
	}
	data := struct {
		VMType, ProjectTree, Disk, Memory string
		CPUs                              int
		NestedVirt                        bool
		Images                            []GuestImage
	}{vmType, projectTree, o.Disk, o.Memory, o.CPUs, o.NestedVirt, GuestImages}
	var buf bytes.Buffer
	if err := tpl.Execute(&buf, data); err != nil {
		return "", err
	}
	return buf.String(), nil
}
